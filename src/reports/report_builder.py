def build_pros_cons_table(pros: list, cons: list) -> Table:
    """Renders a side-by-side list of strengths and risks."""
    pros_show = pros[:3]
    cons_show = cons[:3]

    if not pros_show:
        pros_show = ["No major financial strengths identified."]
    if not cons_show:
        cons_show = ["No major financial concerns identified."]

    pro_flowables = [
        Paragraph("<b>Key Financial Strengths (Pros)</b>", bullet_heading_pro)
    ]
    for p_text in pros_show:
        bullet_html = (
            f"<font color='{PRO_GREEN.hexval()}'><b>&#9656;</b></font> {p_text}"
        )
        pro_flowables.append(Paragraph(bullet_html, bullet_style))

    con_flowables = [
        Paragraph("<b>Key Financial Concerns (Cons)</b>", bullet_heading_con)
    ]
    for c_text in cons_show:
        bullet_html = f"<font color='{CON_RED.hexval()}'><b>&#9656;</b></font> {c_text}"
        con_flowables.append(Paragraph(bullet_html, bullet_style))

    pros_cons = Table([[pro_flowables, con_flowables]], colWidths=[256, 267])
    pros_cons.setStyle(
        TableStyle(
            [
                ("VALIGN", (0, 0), (-1, -1), "TOP"),
                ("LEFTPADDING", (0, 0), (-1, -1), 0),
                ("RIGHTPADDING", (0, 0), (-1, -1), 10),
                ("TOPPADDING", (0, 0), (-1, -1), 0),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 0),
            ]
        )
    )
    return pros_cons


