def calculate_trend(latest: float, prev: float, is_debt: bool = False) -> tuple:
    """Computes arrow direction, color, and trend text label based on relative changes."""
    if pd.isnull(latest) or pd.isnull(prev) or latest is None or prev is None:
        return "→", TEXT_LIGHT, "Stable (N/A)"

    if prev == 0.0:
        rel_change = latest - prev
    else:
        rel_change = (latest - prev) / abs(prev)

    if abs(rel_change) <= 0.02:
        return "→", TEXT_LIGHT, "Stable"

    if is_debt:
        # Debt ratio: lower is better
        if rel_change < -0.02:
            return "↑", PRO_GREEN, "Improved"
        else:
            return "↓", CON_RED, "Declined"
    else:
        # Other ratios: higher is better
        if rel_change > 0.02:
            return "↑", PRO_GREEN, "Improved"
        else:
            return "↓", CON_RED, "Declined"


def make_trend_cell(
    label: str,
    latest_val: float,
    prev_val: float,
    arrow: str,
    color: colors.Color,
    label_text: str,
    is_pct: bool = False,
    is_curr: bool = False,
) -> Paragraph:
    """Builds a formatted Paragraph with YoY trend information."""

    def fmt(val):
        if pd.isnull(val) or val is None:
            return "N/A"
        if is_curr:
            return f"\u20b9{val:,.0f}Cr"
        if is_pct:
            return f"{val:.1f}%"
        return f"{val:.2f}x" if "D/E" in label else f"{val:.2f}"

    l_str = fmt(latest_val)
    p_str = fmt(prev_val)

    text_html = (
        f"<b>{label} YoY Trend</b><br/>"
        f"<font size='7' color='{TEXT_LIGHT.hexval()}'>{p_str} &rarr; {l_str}</font><br/>"
        f"<font color='{color.hexval()}'><b>{arrow} {label_text}</b></font>"
    )
    return Paragraph(text_html, trend_label_style)


